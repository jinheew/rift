def env_key(task: str, shift: str, level: float | str) -> str:
    if shift in ("friction", "gravity"):
        level = float(level)
    return "{}-{}-{}".format(task, shift.replace("_", "-"), level)


def normalized_score(task: str, shift: str, level: float | str,
                     total_return: float) -> float:
    key = env_key(task, shift, level)
    if key not in REF_MIN_SCORE:
        raise KeyError(
            "no reference score for {!r}"
        )
    low, high = REF_MIN_SCORE[key], REF_MAX_SCORE[key]
    return 100.0 * (total_return - low) / (high - low)
